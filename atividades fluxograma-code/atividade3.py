# Crie um fluxograma que leia duas notas de um aluno, calcule a média e mostre o resultado da média.
nota1 = int(input("Por favor Joãozinho, descreva a sua nota no primeiro semestre em lógica de programação?:   "))
nota2 = int(input("Qual seria a do segundo semestre?:  "))

media = nota1 + nota2
media1 = media /2

print("Parabéns seu média foi:  ", media1)